import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

# Default fallback values
DEFAULT_AUTHOR = "Hermes Contributor"
DEFAULT_LICENSE = "MIT"
DEFAULT_VERSION = "1.0.0"


def read_skill_frontmatter(skill_path: Path) -> Dict[str, str]:
    """Read frontmatter from SKILL.md."""
    content = (skill_path / "SKILL.md").read_text()
    fm_match = re.search(r'^---\n(.*?)\n---', content, re.DOTALL)
    if not fm_match:
        return {}
    
    fm_text = fm_match.group(1)
    fm = {}
    for line in fm_text.split('\n'):
        if ':' in line:
            key, val = line.split(':', 1)
            fm[key.strip()] = val.strip().strip('"\'')
    return fm


def ensure_frontmatter(skill_path: Path, defaults: Dict) -> bool:
    """Ensure SKILL.md has all required frontmatter fields."""
    fm = read_skill_frontmatter(skill_path)
    content = (skill_path / "SKILL.md").read_text()
    
    changes = []
    
    if 'version' not in fm:
        changes.append(f"version: {defaults.get('version', DEFAULT_VERSION)}")
    if 'author' not in fm:
        changes.append(f"author: {defaults.get('author', DEFAULT_AUTHOR)}")
    if 'license' not in fm:
        changes.append(f"license: {defaults.get('license', DEFAULT_LICENSE)}")
    
    if not changes:
        return False
    
    # Add fields after description line
    lines = content.split('\n')
    new_lines = []
    for line in lines:
        new_lines.append(line)
        if line.startswith('description:') and '---' not in line:
            for change in changes:
                new_lines.append(change)
    
    (skill_path / "SKILL.md").write_text('\n'.join(new_lines))
    print(f"  Updated frontmatter: {', '.join(changes)}")
    return True


